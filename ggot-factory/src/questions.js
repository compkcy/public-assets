export function visibleQuestions(p) {
  const types = p?.types || [], effects = p?.effects || [];
  if (isPack(p)) return questions.filter(([, scope]) => scope === 'pack' || (PACK_TYPES.includes(scope) && types.includes(scope)));
  return questions.filter(([, scope]) => scope === 'common' || types.includes(scope) || effects.includes(scope)
    || (scope === '선크림' && effects.includes('자외선 차단')));
}
